  /// 🔍 وەرگێڕانی کلیلێک — چاککراو
  static String t(String key, String lang) {
    // ✅ کوردی: Dictionary ی تایبەت
    if (lang == 'ku') {
      return _kurdishTranslations[key] ?? key;
    }

    // ✅ زمانەکانی تر
    return _translations[lang]?[key] ?? key;
  }

  /// 🔍 وەرگێڕان لەگەڵ پارامەتەر ({count})
  static String tWithParams(
      String key,
      String lang,
      Map<String, String> params,
      ) {
    var text = t(key, lang);
    params.forEach((k, v) {
      text = text.replaceAll('{$k}', v);
    });
    return text;
  }

  /// 🔍 پشکنین ئەگەر کلیلێک هەبێت
  static bool hasKey(String key, String lang) {
    if (lang == 'ku') {
      return _kurdishTranslations.containsKey(key);
    }
    return _translations[lang]?.containsKey(key) ?? false;
  }

  /// 🔍 وەرگرتنی هەموو کلیلەکانی زمانێک
  static List<String> getKeys(String lang) {
    if (lang == 'ku') {
      return _kurdishTranslations.keys.toList();
    }
    return _translations[lang]?.keys.toList() ?? [];
  }
